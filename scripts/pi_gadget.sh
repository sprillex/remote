#!/bin/bash
# Multi-function composite gadget script (HID + Mass Storage + RNDIS) for Raspberry Pi Zero
# Configures USB ConfigFS

set -e

# Load necessary modules
modprobe libcomposite || true

# ConfigFS variables
CONFIGFS_HOME="/sys/kernel/config/usb_gadget"
GADGET_NAME="pi_gadget"
GADGET_DIR="${CONFIGFS_HOME}/${GADGET_NAME}"
SERIAL="1000000000000000"
MANUF="PiFoundation"
PROD="Pi Zero Composite Gadget"

# Ensure root privileges
if [ "$EUID" -ne 0 ]; then
  echo "Please run as root."
  return 1 2>/dev/null
fi

# Create gadget directory
mkdir -p "${GADGET_DIR}"
cd "${GADGET_DIR}" || return 1

# Gadget details
echo 0x1d6b > idVendor  # Linux Foundation
echo 0x0104 > idProduct # Multifunction Composite Gadget
echo 0x0100 > bcdDevice # v1.0.0
echo 0x0200 > bcdUSB    # USB 2.0

# Set string descriptors
mkdir -p strings/0x409
echo "${SERIAL}" > strings/0x409/serialnumber
echo "${MANUF}" > strings/0x409/manufacturer
echo "${PROD}" > strings/0x409/product

# Configuration
CONFIG_DIR="configs/c.1"
mkdir -p "${CONFIG_DIR}"
echo 250 > "${CONFIG_DIR}/MaxPower"
mkdir -p "${CONFIG_DIR}/strings/0x409"
echo "Composite Config" > "${CONFIG_DIR}/strings/0x409/configuration"

# --- Function 1: HID (Keyboard) ---
mkdir -p functions/hid.usb0
echo 1 > functions/hid.usb0/protocol
echo 1 > functions/hid.usb0/subclass
echo 8 > functions/hid.usb0/report_length
# Standard keyboard report descriptor
echo -ne \\x05\\x01\\x09\\x06\\xa1\\x01\\x05\\x07\\x19\\xe0\\x29\\xe7\\x15\\x00\\x25\\x01\\x75\\x01\\x95\\x08\\x81\\x02\\x95\\x01\\x75\\x08\\x81\\x03\\x95\\x05\\x75\\x01\\x05\\x08\\x19\\x01\\x29\\x05\\x91\\x02\\x95\\x01\\x75\\x03\\x91\\x03\\x95\\x06\\x75\\x08\\x15\\x00\\x25\\x65\\x05\\x07\\x19\\x00\\x29\\x65\\x81\\x00\\xc0 > functions/hid.usb0/report_desc

# --- Function 2: Mass Storage ---
mkdir -p functions/mass_storage.usb0
# Create a dummy backing file if it doesn't exist (1MB for demonstration)
BACKING_FILE="/pi_usb_disk.img"
if [ ! -f "${BACKING_FILE}" ]; then
  dd if=/dev/zero of="${BACKING_FILE}" bs=1M count=1
  mkfs.vfat "${BACKING_FILE}"
fi
echo "${BACKING_FILE}" > functions/mass_storage.usb0/lun.0/file

# --- Function 3: RNDIS (Network) ---
mkdir -p functions/rndis.usb0
# Set up MAC addresses (optional, can be generated by kernel)
HOST_MAC="42:63:65:12:34:56"
DEV_MAC="42:63:65:65:43:21"
echo "${HOST_MAC}" > functions/rndis.usb0/host_addr
echo "${DEV_MAC}" > functions/rndis.usb0/dev_addr

# Link functions to configuration
ln -s functions/hid.usb0 "${CONFIG_DIR}"
ln -s functions/mass_storage.usb0 "${CONFIG_DIR}"
ln -s functions/rndis.usb0 "${CONFIG_DIR}"

# Enable gadget by binding to UDC
# Get the available UDC driver (usually dwc2 on Pi Zero)
UDC_FILE="/sys/class/udc"
if [ -d "${UDC_FILE}" ]; then
  UDC_DRIVER=$(find "${UDC_FILE}" -mindepth 1 -maxdepth 1 -printf "%f\n" | head -n 1)
  if [ -n "${UDC_DRIVER}" ]; then
    echo "${UDC_DRIVER}" > UDC
    echo "Composite gadget successfully initialized and bound to ${UDC_DRIVER}."
  else
    echo "No UDC driver found to bind."
  fi
else
    echo "UDC path not found. Is this a Raspberry Pi configured for OTG?"
fi
